#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
generation/02_generate_bbox.py

[Role]
1. Reads scenario JSONs generated by step 01.
2. Uses GroundingDINO to detect the 'occludee' in the original image.
3. Generates bounding boxes following specific geometric rules:
   - Constraints: Min 1/16, Max 1/4 of image area.
   - Cat A, C: Shrink to 1/4 area, keeping the BOTTOM edge fixed.
   - Cat B: Move to Bottom-Left corner with padding.
   - Cat E: Add secondary box in opposite quadrant.
"""

import json
import sys
import math
import argparse
import os
from pathlib import Path
from tqdm import tqdm
from PIL import Image
from dotenv import load_dotenv

# --- Import Setup ---
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.append(str(PROJECT_ROOT))

from nybench.detection.grounding_dino import GroundingDetector

def normalize_bbox(bbox, w, h):
    if not bbox or bbox == [0, 0, 0, 0]:
        return [0.0, 0.0, 0.0, 0.0]
    
    return [
        max(0.0, min(1.0, bbox[0] / w)),
        max(0.0, min(1.0, bbox[1] / h)),
        max(0.0, min(1.0, bbox[2] / w)),
        max(0.0, min(1.0, bbox[3] / h))
    ]

def calculate_box_area(bbox):
    """bbox: [x1, y1, x2, y2]"""
    w = max(0, bbox[2] - bbox[0])
    h = max(0, bbox[3] - bbox[1])
    return w * h

def get_box_center(bbox):
    return ((bbox[0] + bbox[2]) / 2, (bbox[1] + bbox[3]) / 2)

def clamp_bbox(bbox, img_w, img_h):
    """Ensure bbox stays within image boundaries."""
    return [
        max(0, min(bbox[0], img_w)),
        max(0, min(bbox[1], img_h)),
        max(0, min(bbox[2], img_w)),
        max(0, min(bbox[3], img_h))
    ]

def resize_bbox_to_constraints(bbox, img_w, img_h, min_ratio=1/16, max_ratio=1/4):
    """
    Adjusts the bbox to be within [img_area * min_ratio, img_area * max_ratio].
    Keeps the center of the box fixed.
    """
    if not bbox or bbox == [0, 0, 0, 0]:
        cx, cy = img_w / 2, img_h / 2
        target_area = img_w * img_h * 0.1 
        side = math.sqrt(target_area)
        return [cx - side/2, cy - side/2, cx + side/2, cy + side/2]

    img_area = img_w * img_h
    box_area = calculate_box_area(bbox)
    
    min_area = img_area * min_ratio
    max_area = img_area * max_ratio
    
    if min_area <= box_area <= max_area:
        return bbox

    current_w = bbox[2] - bbox[0]
    current_h = bbox[3] - bbox[1]
    
    if box_area < min_area:
        target_area = min_area
    else:
        target_area = max_area
        
    scale_factor = math.sqrt(target_area / (box_area + 1e-6))
    
    new_w = current_w * scale_factor
    new_h = current_h * scale_factor
    
    cx, cy = get_box_center(bbox)
    
    new_bbox = [
        cx - new_w / 2,
        cy - new_h / 2,
        cx + new_w / 2,
        cy + new_h / 2
    ]
    
    return clamp_bbox(new_bbox, img_w, img_h)

def get_turn2_bbox(category, turn1_bbox, img_w, img_h):
    """
    Calculates Turn 2 bbox based on scenario category.
    """
    if category in ['D', 'E']:
        # Remove -> No box
        return None

    t1_w = turn1_bbox[2] - turn1_bbox[0]
    t1_h = turn1_bbox[3] - turn1_bbox[1]
    t1_cx = (turn1_bbox[0] + turn1_bbox[2]) / 2
    t1_bottom = turn1_bbox[3] # y2

    # --- [Category A, C] Bottom Fixed, 1/4 Area Shrink ---
    if category in ['A', 'C']: 
        # Logic: 
        # 1. Width & Height become 0.5x (Area 0.25x)
        # 2. Horizontal Center (cx) stays same.
        # 3. Bottom Edge (y2) stays same.
        
        new_w = t1_w * 0.5
        new_h = t1_h * 0.5
        
        new_x1 = t1_cx - (new_w / 2)
        new_x2 = t1_cx + (new_w / 2)
        new_y2 = t1_bottom  # Bottom Fixed
        new_y1 = new_y2 - new_h
        
        return clamp_bbox([new_x1, new_y1, new_x2, new_y2], img_w, img_h)
    # -----------------------------------------------------

    # --- [Category B] Bottom-Left Corner with Padding ---
    if category == 'B':
        padding = 10 # pixels
        
        # Anchor to bottom-left
        new_x1 = padding
        new_y2 = img_h - padding
        
        new_x2 = new_x1 + t1_w
        new_y1 = new_y2 - t1_h
        
        # Boundary check (if object is bigger than image/padding)
        if new_y1 < 0: new_y1 = 0
        if new_x2 > img_w: new_x2 = img_w

        return clamp_bbox([new_x1, new_y1, new_x2, new_y2], img_w, img_h)
    # -----------------------------------------------------

    return None

def get_secondary_bbox_for_category_E(primary_bbox, img_w, img_h):
    """
    For Category E (Add Two), place secondary box in opposite quadrant.
    """
    p_cx, p_cy = get_box_center(primary_bbox)
    
    is_left = p_cx < img_w / 2
    is_top = p_cy < img_h / 2
    
    target_x_ratio = 0.75 if is_left else 0.25
    target_y_ratio = 0.75 if is_top else 0.25
    
    target_cx = img_w * target_x_ratio
    target_cy = img_h * target_y_ratio
    
    # Same size as primary (or adjusted logic if needed)
    w = (primary_bbox[2] - primary_bbox[0])
    h = (primary_bbox[3] - primary_bbox[1])
    
    return clamp_bbox([
        target_cx - w/2,
        target_cy - h/2,
        target_cx + w/2,
        target_cy + h/2
    ], img_w, img_h)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--scenarios_dir", type=str, default="../data/scenarios")
    parser.add_argument("--images_dir", type=str, default="../data/images")
    args = parser.parse_args()

    load_dotenv()

    # Initialize Detector
    try:
        # GroundingDINO Detector uses DDS_TOKEN from env
        detector = GroundingDetector(min_score=0.20) 
        print("Initialized GroundingDINO Detector.")
    except Exception as e:
        print(f"Error initializing detector: {e}")
        print("Tip: Check if DDS_TOKEN is set correctly in .env")
        return

    scenario_files = sorted(list(Path(args.scenarios_dir).glob("*.json")))

    print(f"Found {len(scenario_files)} scenario files.")

    for json_file in tqdm(scenario_files, desc="Detecting Occludees"):
        with open(json_file, 'r') as f:
            data = json.load(f)
        
        session_id = data.get('session_id', json_file.stem) # e.g. "0001_s1"
        image_id = session_id.split('_')[0]                 # e.g. "0001"
        
        img_path = Path(data.get('original_image', ''))

        if not img_path.exists():
            p1 = Path(args.images_dir) / session_id / "turn0.png"
            p2 = Path(args.images_dir) / image_id / "turn0.png"

            if p1.exists():
                img_path = p1
            elif p2.exists():
                img_path = p2
            else:
                candidates = sorted(list(Path(args.images_dir).glob(f"{image_id}_*/turn0.png")))
                if candidates:
                    img_path = candidates[0]
        
        if not img_path.exists():
            print(f"[WARN] Image not found for {session_id} (Tried ID: {image_id})")
            continue
            
        with Image.open(img_path) as img:
            img_w, img_h = img.size
        
        category = data.get('category')
        occludee_desc = data.get('occludee')
        
        if not category or not occludee_desc:
            print(f"[SKIP] Missing category/occludee in {json_file.name}")
            continue

        # 1. Raw Detection (GroundingDINO)
        try:
            result = detector.predict(img_path, occludee_desc)
            raw_bbox = result['best_bbox'] 
        except:
            raw_bbox = [0, 0, 0, 0]

        # 2. Processed Occluder T1 (Red Box)
        final_t1_bbox = resize_bbox_to_constraints(raw_bbox, img_w, img_h)
        
        # 3. Processed Occluder T2 (Green Box)
        final_t2_bbox = get_turn2_bbox(category, final_t1_bbox, img_w, img_h)
        
        # 4. Secondary Object (Category E)
        sec_t1_bbox = None
        sec_t2_bbox = None
        
        if category == 'E':
            sec_t1_bbox = get_secondary_bbox_for_category_E(final_t1_bbox, img_w, img_h)
            sec_t2_bbox = sec_t1_bbox

        data['occludee_turn1_bbox'] = normalize_bbox(raw_bbox, img_w, img_h)
        data['occluder_turn1_bbox'] = normalize_bbox(final_t1_bbox, img_w, img_h)
        
        if final_t2_bbox:
            data['occluder_turn2_bbox'] = normalize_bbox(final_t2_bbox, img_w, img_h)
        else:
            data['occluder_turn2_bbox'] = None
        
        if sec_t1_bbox:
            data['occluder*_turn1_bbox'] = normalize_bbox(sec_t1_bbox, img_w, img_h)
            data['occluder*_turn2_bbox'] = normalize_bbox(sec_t2_bbox, img_w, img_h)
        else:
            data['occluder*_turn1_bbox'] = None
            data['occluder*_turn2_bbox'] = None

        with open(json_file, 'w') as f:
            json.dump(data, f, indent=2)

    print("\nDone! Bounding boxes added.")

if __name__ == "__main__":
    main()